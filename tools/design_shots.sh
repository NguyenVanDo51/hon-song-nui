#!/usr/bin/env bash
# Real screenshots for the design-system pages (docs/design/man-hinh.html, noi-dung.html):
# every menu screen (landscape + portrait), every level's opening board, in-game popups from the UI drivers.
# Output (gitignored, regenerate after a UI change): docs/design/shots/*.png + shots.js (list)
# Needs a window (display on): headless renders nothing. Uses profile test / driver, never the player's save.
# usage: [SHOT_LANG=en] tools/design_shots.sh [screens|levels|ui|all]   (default all; SHOT_LANG=en -> files *_en.png)
set -uo pipefail
cd "$(dirname "$0")/.."
WHAT="${1:-all}"
L="${SHOT_LANG:-vi}"
SUF=""; [ "$L" = vi ] || SUF="_$L"
OUT="$PWD/docs/design/shots"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT
mkdir -p "$OUT"

# one windowed run; keeps the last periodic shot as $OUT/<name>.png
snap() { # name resolution wait_s args...
	local name="$1" res="$2" wait="$3"; shift 3
	rm -rf "$TMP/s"; mkdir -p "$TMP/s"
	timeout 60 godot --path . --resolution "$res" -- profile=test lang="$L" shots="$TMP/s" shot_every=0.5 tag=x quit_at="$wait" "$@" > /dev/null 2>&1
	local last; last="$(ls "$TMP/s"/x_*.png 2>/dev/null | tail -1)"
	if [ -n "$last" ]; then cp "$last" "$OUT/$name$SUF.png"; echo "ok   $name$SUF"; else echo "FAIL $name$SUF"; fi
}

if [ "$WHAT" = screens ] || [ "$WHAT" = all ]; then
	for sc in title levels skirmish duel codex; do
		snap "screen_${sc}" 1280x720 2.5 screen=$sc
		snap "screen_${sc}_portrait" 540x1170 2.5 screen=$sc
	done
	snap "game_m07" 1280x720 3 mission=m07 fresh nointro
	snap "game_m07_portrait" 540x1170 3 mission=m07 fresh nointro
fi

if [ "$WHAT" = levels ] || [ "$WHAT" = all ]; then
	for f in content/levels/*.gd; do
		id="$(basename "$f" .gd)"
		snap "level_$id" 1280x720 2 mission="$id" fresh nointro
	done
fi

if [ "$WHAT" = ui ] || [ "$WHAT" = all ]; then
	# drivers click through the real UI and call main.shot("<state>") at each popup / card
	run_driver() { # label args...
		local label="$1"; shift
		rm -rf "$TMP/d"; mkdir -p "$TMP/d"
		timeout 240 godot --path . --resolution 1280x720 -s "$@" lang="$L" shots="$TMP/d" shot_every=100000 > "$TMP/$label.log" 2>&1
		local n=0
		for p in "$TMP/d"/*.png; do
			[ -e "$p" ] || continue
			case "$(basename "$p")" in s_*) continue ;; esac # periodic shot, not a named state
			cp "$p" "$OUT/ui_$(basename "$p" .png)$SUF.png"; n=$((n + 1))
		done
		echo "ok   $label: $n states"
	}
	run_driver design sim/design_driver.gd --
	run_driver click sim/click_driver.gd -- mission=m02 fresh nointro
	for t in t01 t02 t03; do run_driver "tut_$t" sim/tut_driver.gd -- mission=$t fresh; done
fi

{
	echo "// generated by tools/design_shots.sh — do not edit"
	printf 'window.SHOTS = { "taken": "%s", "files": [\n' "$(date '+%Y-%m-%d %H:%M') @ $(git rev-parse --short HEAD)"
	for p in "$OUT"/*.png; do [ -e "$p" ] && printf '  "%s",\n' "$(basename "$p")"; done
	echo "] };"
} > "$OUT/shots.js"
echo "shots: $(ls "$OUT"/*.png 2>/dev/null | wc -l | tr -d ' ') png -> $OUT ($(du -sh "$OUT" | cut -f1))"
