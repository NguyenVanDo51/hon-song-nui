"""Bundle every glyph the game uses that Be Vietnam Pro lacks (web builds have no system fonts).
- emoji -> Noto Emoji PNGs (Apache 2.0) in assets/emoji/, packed at runtime into a bitmap fallback font (scripts/ui/emoji_font.gd)
- other symbols (★ ✕ ♪ …) -> subset of Noto Sans Symbols 2 (OFL) in assets/fonts/SymbolsSubset.ttf
usage: python tools/build_fonts.py <dir with NotoSansSymbols2.ttf>      (re-run after adding text with new emoji)
"""
import glob, os, sys, urllib.request
from fontTools.ttLib import TTFont
from fontTools import subset

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
IGNORE = {0x200D, 0xFE0F, 0xFE0E}
PNG = "https://raw.githubusercontent.com/googlefonts/noto-emoji/main/2D/png/128/emoji_u%x.png"

def used_chars():
    chars = set()
    for f in glob.glob(os.path.join(ROOT, "content", "**", "*.gd"), recursive=True) + glob.glob(os.path.join(ROOT, "scripts", "**", "*.gd"), recursive=True):
        chars |= set(open(f, encoding="utf-8").read())
    return {ord(c) for c in chars if ord(c) > 127}

def main():
    src = sys.argv[1]
    bvp = TTFont(os.path.join(ROOT, "assets/fonts/BeVietnamPro-Regular.ttf")).getBestCmap()
    sym_font = os.path.join(src, "NotoSansSymbols2.ttf")
    sym = TTFont(sym_font).getBestCmap()
    missing = sorted(c for c in used_chars() if c not in bvp and c not in IGNORE)
    edir = os.path.join(ROOT, "assets", "emoji")
    os.makedirs(edir, exist_ok=True)
    emoji, symbols, none = [], [], []
    for c in missing:
        path = os.path.join(edir, "emoji_u%x.png" % c)
        if os.path.exists(path):
            emoji.append(c); continue
        try:
            with urllib.request.urlopen(PNG % c, timeout=30) as r:
                data = r.read()
            open(path, "wb").write(data)
            emoji.append(c)
        except Exception:
            (symbols if c in sym else none).append(c)
    if symbols:
        opts = subset.Options()
        opts.name_IDs = ["*"]; opts.notdef_outline = True
        s = subset.Subsetter(opts)
        f = TTFont(sym_font)
        s.populate(unicodes=symbols)
        s.subset(f)
        # borrow Be Vietnam Pro's line metrics so a fallback glyph never makes a line taller
        ref = TTFont(os.path.join(ROOT, "assets/fonts/BeVietnamPro-Regular.ttf"))
        k = f["head"].unitsPerEm / ref["head"].unitsPerEm
        for tab, keys in (("hhea", ["ascent", "descent", "lineGap"]), ("OS/2", ["sTypoAscender", "sTypoDescender", "sTypoLineGap", "usWinAscent", "usWinDescent"])):
            for key in keys:
                setattr(f[tab], key, int(round(getattr(ref[tab], key) * k)))
        f.save(os.path.join(ROOT, "assets/fonts/SymbolsSubset.ttf"))
    with open(os.path.join(edir, "manifest.gd"), "w", encoding="utf-8", newline="\n") as m:
        m.write("extends RefCounted\n## generated by tools/build_fonts.py: codepoints with a PNG here (emoji_u<hex>.png)\n\n")
        m.write("const CODES := [%s]\n" % ", ".join("0x%x" % c for c in emoji))
    print("emoji", len(emoji), "symbols", [chr(c) for c in symbols], "uncovered", ["U+%04X" % c for c in none])

main()
