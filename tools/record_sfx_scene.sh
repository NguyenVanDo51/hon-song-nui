#!/usr/bin/env bash
# Records a real bot-vs-bot clip (picture + game audio) for the design-system page (docs/design/index.html, "Cảnh game").
# Godot movie maker -> PNG frames + WAV; `sfxlog` flag -> which sound fired on which frame.
# Output (gitignored, regenerate after changing a sound): docs/design/scene/{scene.m4a, f00000.jpg…, scene.js}
# Needs a window (display on). macOS only (afconvert, sips).
# usage: tools/record_sfx_scene.sh [mission=m07] [seconds=150]
set -euo pipefail
cd "$(dirname "$0")/.."
MISSION="${1:-m07}"
SEC="${2:-150}"
FPS=12   # recorded
STEP=2   # keep every 2nd frame -> 6 fps flipbook
OUT=docs/design/scene
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

echo "record: $MISSION, ${SEC}s @ ${FPS} fps -> $TMP"
timeout $((SEC * 6 + 120)) godot --path . --write-movie "$TMP/clip.png" --fixed-fps $FPS --resolution 1280x720 \
	-- mission="$MISSION" fresh profile=test lang=vi bot speed=1 zoom sfxlog quit_at="$SEC" > "$TMP/log.txt" 2>&1 || true
[ -f "$TMP/clip.wav" ] || { echo "no clip.wav (window needed?)"; tail -20 "$TMP/log.txt"; exit 1; }

rm -rf "$OUT"
mkdir -p "$OUT"
afconvert -f m4af -d aac -b 128000 "$TMP/clip.wav" "$OUT/scene.m4a"

n=0
for f in "$TMP"/clip*.png; do
	i=$((10#$(basename "$f" .png | sed 's/^clip//')))
	if [ $((i % STEP)) -eq 0 ]; then
		sips -Z 960 -s format jpeg -s formatOptions 70 "$f" --out "$OUT/$(printf 'f%05d.jpg' $((i / STEP)))" > /dev/null
		n=$((n + 1))
	fi
done

{
	echo "// generated by tools/record_sfx_scene.sh — do not edit"
	printf 'window.SCENE = { "mission": "%s", "fps": %s, "frames": %d, "recorded": "%s", "events": [\n' \
		"$MISSION" $((FPS / STEP)) "$n" "$(date '+%Y-%m-%d %H:%M') @ $(git rev-parse --short HEAD)"
	grep '^SFXLOG ' "$TMP/log.txt" | awk -v fps=$FPS '{ printf "  [%.3f, \"%s\"],\n", $2 / fps, $3 }'
	echo "] };"
} > "$OUT/scene.js"
echo "scene: $n frames, $(grep -c '^SFXLOG ' "$TMP/log.txt") sound events -> $OUT ($(du -sh "$OUT" | cut -f1))"
